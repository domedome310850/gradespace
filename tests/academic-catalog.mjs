import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {extractCatalog} from '../scripts/export-academic-catalog.mjs';
const root=new URL('../',import.meta.url);
const staged=JSON.parse(readFileSync(new URL('data/staging/cu-legacy-catalog.json',root),'utf8'));
const actual=extractCatalog(readFileSync(new URL('public/index.html',root),'utf8'),staged.source.blob_sha);
assert.deepEqual(actual,staged,'Regenerate staging snapshot if embedded catalog or plans change');
assert.equal(new Set(staged.courses.map(x=>x.id)).size,staged.courses.length);
assert.ok(staged.courses.every(x=>x.institution_id==='cu'&&x.id==='cu:'+x.code&&x.status==='legacy_unverified'));
assert.ok(staged.study_plans.every(x=>x.status==='legacy_unverified'));
assert.deepEqual(staged.quality.unresolved_course_refs,[]);
const make=(courses,plans)=>'var CATALOG = (function(){ var COURSES = '+JSON.stringify(courses)+'; var PLANS = '+JSON.stringify(plans)+'; })();';
const test=extractCatalog(make({'1234567':{n:'Quoted } and ] and " title',cr:1.5}},[{id:'p',items:[{c:'7654321'}]}]),'fixture');
assert.equal(test.courses[0].credits,1.5);
assert.deepEqual(test.quality.unresolved_course_refs,['cu:7654321']);
assert.throws(()=>extractCatalog(make({'1234567':{n:'Invalid',cr:-1}},[]),'fixture'),/Invalid legacy course/);
assert.throws(()=>extractCatalog(make({},[{id:'p',items:[]},{id:'p',items:[]}]),'fixture'),/duplicate legacy plan/);
assert.throws(()=>extractCatalog('','fixture'),/CATALOG missing/);
console.log('Academic staging checks passed: '+staged.courses.length+' courses / '+staged.study_plans.length+' plans');
